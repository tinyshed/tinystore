//! The Go side: a struct a message, read and written a field at a time
//! through internal/wire's reader and writer, a constant a method, laid out as
//! gofmt lays it out, so that the file needs no formatter after it.
//!
//! ```text
//! kv.Branch { 1 handle: uint, 2 under: [key] }
//!
//! type KvBranch struct {
//!     Handle uint64   `wire:"1,handle"`
//!     Under  []string `wire:"2,under"`
//! }
//! ```
//!
//! A field marked `?` is a pointer, nil while absent; any other is left out
//! at its zero value and reads back as it, as the Rust side does.

use std::fmt::Write as _;

use super::names::type_name;
use super::schema::{Field, Kind, Message, Schema};

pub(crate) fn write(schema: &Schema) -> String {
    let mut out = String::new();
    out.push_str("// Code generated by crates/protocol from protocol/*.wire; DO NOT EDIT.\n");
    out.push_str("// `just protocol` writes it again.\n\npackage wire\n\n");
    if schema
        .messages
        .iter()
        .flat_map(|message| &message.fields)
        .any(|field| field.kind == Kind::Float && !field.optional)
    {
        out.push_str("import \"math\"\n\n");
    }
    write_methods(&mut out, schema);
    out.push('\n');
    write_new_message(&mut out, schema);
    for message in &schema.messages {
        out.push('\n');
        write_message(&mut out, message);
    }
    out
}

/// `NewMessage`: an empty message by its name in the schema, for whoever
/// reads a message it knows only by name, as the vectors name theirs.
fn write_new_message(out: &mut String, schema: &Schema) {
    out.push_str("// NewMessage is an empty message by its name in the schema, nil for a name\n");
    out.push_str("// the schema does not have.\nfunc NewMessage(name string) Message {\n\tswitch name {\n");
    for message in &schema.messages {
        let _ = writeln!(out, "\tcase \"{}\":\n\t\treturn &{}{{}}", message.name, type_name(&message.name));
    }
    out.push_str("\t}\n\treturn nil\n}\n");
}

fn write_methods(out: &mut String, schema: &Schema) {
    out.push_str("// The methods, by their numbers on the wire.\nconst (\n");
    let rows: Vec<Row> = schema
        .methods
        .iter()
        .map(|method| Row {
            comments: method.doc.clone(),
            cells: vec![method_const(&method.name), format!("= 0x{:04x}", method.id)],
        })
        .collect();
    write_rows(out, &rows);
    out.push_str(")\n\n");
    out.push_str("// methodNames is every method by its name in the schema.\n");
    out.push_str("var methodNames = []struct {\n\tname string\n\tid   uint16\n}{\n");
    for method in &schema.methods {
        let _ = writeln!(out, "\t{{\"{}\", {}}},", method.name, method_const(&method.name));
    }
    out.push_str("}\n\n");
    out.push_str("// Methods is every method by its name in the schema.\nfunc Methods() map[string]uint16 {\n");
    out.push_str("\tmethods := make(map[string]uint16, len(methodNames))\n");
    out.push_str("\tfor _, method := range methodNames {\n\t\tmethods[method.name] = method.id\n\t}\n");
    out.push_str("\treturn methods\n}\n");
}

fn method_const(name: &str) -> String {
    format!("Method{}", type_name(name))
}

fn write_message(out: &mut String, message: &Message) {
    let name = type_name(&message.name);
    let _ = writeln!(out, "// {name} is the schema's {}.", message.name);
    if !message.doc.is_empty() {
        out.push_str("//\n");
        for line in &message.doc {
            let _ = writeln!(out, "// {line}");
        }
    }
    if message.fields.is_empty() {
        let _ = writeln!(out, "type {name} struct{{}}\n");
    } else {
        let _ = writeln!(out, "type {name} struct {{");
        let rows: Vec<Row> = message
            .fields
            .iter()
            .map(|field| Row {
                comments: field.doc.iter().cloned().collect(),
                cells: vec![
                    go_field(&field.name),
                    field_type(field),
                    format!("`wire:\"{},{}\"`", field.number, field.name),
                ],
            })
            .collect();
        write_rows(out, &rows);
        out.push_str("}\n\n");
    }
    let mut fields: Vec<&Field> = message.fields.iter().collect();
    fields.sort_by_key(|field| field.number);
    write_writer(out, &name, &fields);
    write_reader(out, &name, &fields);
    write_is_zero(out, &name, &fields);
}

/// A line of a block gofmt aligns: its cells, the last left as it is, and
/// the comment lines above it, which begin a new run of aligned lines.
struct Row {
    comments: Vec<String>,
    cells: Vec<String>,
}

/// Writes rows a tab in, each cell but the last padded to the widest of its
/// column among the rows of its run, as gofmt does.
fn write_rows(out: &mut String, rows: &[Row]) {
    let mut start = 0;
    while start < rows.len() {
        let mut end = start + 1;
        while end < rows.len() && rows[end].comments.is_empty() {
            end += 1;
        }
        let run = &rows[start..end];
        let columns = run[0].cells.len();
        let widths: Vec<usize> =
            (0..columns).map(|at| run.iter().map(|row| row.cells[at].chars().count()).max().unwrap_or(0)).collect();
        for row in run {
            for comment in &row.comments {
                let _ = writeln!(out, "\t// {comment}");
            }
            out.push('\t');
            for (at, cell) in row.cells.iter().enumerate() {
                if at + 1 == columns {
                    out.push_str(cell);
                } else {
                    let _ = write!(out, "{cell}{} ", " ".repeat(widths[at] - cell.chars().count()));
                }
            }
            out.push('\n');
        }
        start = end;
    }
}

/// A field as Go names it: exported, its first letter capitalized.
fn go_field(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map_or_else(String::new, |first| first.to_uppercase().chain(chars).collect())
}

fn field_type(field: &Field) -> String {
    let kind = kind_type(&field.kind);
    if field.optional { format!("*{kind}") } else { kind }
}

fn kind_type(kind: &Kind) -> String {
    match kind {
        Kind::Bool => "bool".to_owned(),
        Kind::Uint | Kind::Duration => "uint64".to_owned(),
        Kind::Int | Kind::Int64 | Kind::Time | Kind::Nanos => "int64".to_owned(),
        Kind::Float => "float64".to_owned(),
        Kind::Str | Kind::Json | Kind::Key => "string".to_owned(),
        Kind::Bin => "[]byte".to_owned(),
        Kind::Value => "Raw".to_owned(),
        Kind::Cell => "Cell".to_owned(),
        Kind::List(item) => format!("[]{}", kind_type(item)),
        Kind::Names(item) => format!("map[string]{}", kind_type(item)),
        Kind::Message(name) => type_name(name),
    }
}

/// The writer: each field that holds more than its zero value, or that is
/// present when it is optional, after its number, the map's count kept in a
/// byte until the fields are written.
fn write_writer(out: &mut String, name: &str, fields: &[&Field]) {
    // a value's: a message in a map, which Go does not address, writes too
    let _ = writeln!(out, "func (m {name}) Write(w *Writer) {{");
    if fields.is_empty() {
        out.push_str("\tw.Map(0)\n}\n\n");
        return;
    }
    out.push_str("\thead := w.OpenMap()\n\tn := 0\n");
    for field in fields {
        let member = format!("m.{}", go_field(&field.name));
        let (test, value) = if field.optional {
            // a message's methods take its pointer as it is
            let value = match field.kind {
                Kind::Message(_) => member.clone(),
                _ => format!("*{member}"),
            };
            (format!("{member} != nil"), value)
        } else {
            (nonzero(&field.kind, &member), member)
        };
        let _ = writeln!(out, "\tif {test} {{");
        let _ = writeln!(out, "\t\tw.Uint({})", field.number);
        write_value(out, &field.kind, &value, 2, 0);
        out.push_str("\t\tn++\n\t}\n");
    }
    out.push_str("\tw.CloseMap(head, n)\n}\n\n");
}

/// The lines that write `value` of a kind, `indent` tabs in; a list's items
/// are named by how deep the list is.
fn write_value(out: &mut String, kind: &Kind, value: &str, indent: usize, depth: usize) {
    let tabs = "\t".repeat(indent);
    match kind {
        Kind::List(item) => {
            let each = format!("item{depth}");
            let _ = writeln!(out, "{tabs}w.Array(len({value}))");
            let _ = writeln!(out, "{tabs}for _, {each} := range {value} {{");
            write_value(out, item, &each, indent + 1, depth + 1);
            let _ = writeln!(out, "{tabs}}}");
        }
        Kind::Names(item) => {
            let each = format!("name{depth}");
            // a pointer is dereferenced before it is indexed
            let map = if value.starts_with('*') { format!("({value})") } else { value.to_owned() };
            let _ = writeln!(out, "{tabs}w.Map(len({value}))");
            let _ = writeln!(out, "{tabs}for _, {each} := range SortedNames({value}) {{");
            let _ = writeln!(out, "{tabs}\tw.Str({each})");
            write_value(out, item, &format!("{map}[{each}]"), indent + 1, depth + 1);
            let _ = writeln!(out, "{tabs}}}");
        }
        Kind::Message(_) => {
            let _ = writeln!(out, "{tabs}{value}.Write(w)");
        }
        _ => {
            let _ = writeln!(out, "{tabs}w.{}({value})", writer_of(kind));
        }
    }
}

fn writer_of(kind: &Kind) -> &'static str {
    match kind {
        Kind::Bool => "Bool",
        Kind::Uint | Kind::Duration => "Uint",
        Kind::Int | Kind::Int64 | Kind::Time | Kind::Nanos => "Int",
        Kind::Float => "Float",
        Kind::Str | Kind::Json => "Str",
        Kind::Key => "Key",
        Kind::Bin => "Bin",
        Kind::Value => "Raw",
        Kind::Cell => "Cell",
        Kind::List(_) | Kind::Names(_) | Kind::Message(_) => unreachable!("written by their own lines"),
    }
}

/// The reader: each field's value taken from the body as it comes, a key
/// twice refused and a key the schema does not have read past.
fn write_reader(out: &mut String, name: &str, fields: &[&Field]) {
    let _ = writeln!(out, "func (m *{name}) Read(r *Reader) {{");
    let _ = writeln!(out, "\t*m = {name}{{}}");
    out.push_str("\tvar seen Seen\n\tfor n := r.Map(); n > 0; n-- {\n");
    if fields.is_empty() {
        out.push_str("\t\tr.Field(&seen)\n\t\tr.Skip()\n");
    } else {
        out.push_str("\t\tswitch r.Field(&seen) {\n");
        for field in fields {
            let member = format!("m.{}", go_field(&field.name));
            let _ = writeln!(out, "\t\tcase {}:", field.number);
            match (&field.kind, field.optional) {
                (Kind::Message(_), false) => {
                    let _ = writeln!(out, "\t\t\t{member}.Read(r)");
                }
                (kind, false) if reader_of(kind).is_some() => {
                    let _ = writeln!(out, "\t\t\t{member} = r.{}()", reader_of(kind).unwrap_or_default());
                }
                (kind, optional) => {
                    read_value(out, kind, "v", 3, 0);
                    let _ = writeln!(out, "\t\t\t{member} = {}v", if optional { "&" } else { "" });
                }
            }
        }
        out.push_str("\t\tdefault:\n\t\t\tr.Skip()\n\t\t}\n");
    }
    out.push_str("\t}\n\tr.Leave()\n}\n\n");
}

/// The lines that declare `target` and read a value of a kind into it,
/// `indent` tabs in.
fn read_value(out: &mut String, kind: &Kind, target: &str, indent: usize, depth: usize) {
    let tabs = "\t".repeat(indent);
    match kind {
        Kind::List(item) => {
            let (count, each) = (format!("k{depth}"), format!("item{depth}"));
            let _ = writeln!(out, "{tabs}{target} := {}{{}}", kind_type(kind));
            let _ = writeln!(out, "{tabs}for {count} := r.Array(); {count} > 0; {count}-- {{");
            read_value(out, item, &each, indent + 1, depth + 1);
            let _ = writeln!(out, "{tabs}\t{target} = append({target}, {each})");
            let _ = writeln!(out, "{tabs}}}\n{tabs}r.Leave()");
        }
        Kind::Names(item) => {
            let (count, name, seen, each) =
                (format!("k{depth}"), format!("name{depth}"), format!("seen{depth}"), format!("item{depth}"));
            let _ = writeln!(out, "{tabs}{target} := {}{{}}", kind_type(kind));
            let _ = writeln!(out, "{tabs}{seen} := map[string]struct{{}}{{}}");
            let _ = writeln!(out, "{tabs}for {count} := r.Map(); {count} > 0; {count}-- {{");
            let _ = writeln!(out, "{tabs}\t{name} := r.Name({seen})");
            read_value(out, item, &each, indent + 1, depth + 1);
            let _ = writeln!(out, "{tabs}\t{target}[{name}] = {each}");
            let _ = writeln!(out, "{tabs}}}\n{tabs}r.Leave()");
        }
        Kind::Message(name) => {
            let _ = writeln!(out, "{tabs}var {target} {}", type_name(name));
            let _ = writeln!(out, "{tabs}{target}.Read(r)");
        }
        _ => {
            let _ = writeln!(out, "{tabs}{target} := r.{}()", reader_of(kind).unwrap_or_default());
        }
    }
}

fn reader_of(kind: &Kind) -> Option<&'static str> {
    match kind {
        Kind::List(_) | Kind::Names(_) | Kind::Message(_) => None,
        _ => Some(writer_of(kind)),
    }
}

/// Whether a field that is not optional holds more than its zero value.
fn nonzero(kind: &Kind, member: &str) -> String {
    match kind {
        Kind::Bool => member.to_owned(),
        Kind::Uint | Kind::Duration | Kind::Int | Kind::Int64 | Kind::Time | Kind::Nanos => format!("{member} != 0"),
        Kind::Float => format!("math.Float64bits({member}) != 0"),
        Kind::Str | Kind::Json | Kind::Key => format!("{member} != \"\""),
        Kind::Bin | Kind::List(_) | Kind::Names(_) => format!("len({member}) > 0"),
        Kind::Value => format!("!RawIsZero({member})"),
        Kind::Cell => format!("!CellIsZero({member})"),
        Kind::Message(_) => format!("!{member}.IsZero()"),
    }
}

/// `IsZero`: whether every field holds its zero value, as a field that holds
/// the message is then left out.
fn write_is_zero(out: &mut String, name: &str, fields: &[&Field]) {
    let _ = writeln!(out, "// IsZero says whether {name} writes as no field at all.");
    let _ = writeln!(out, "func (m {name}) IsZero() bool {{");
    let zero: Vec<String> = fields
        .iter()
        .map(|field| {
            let member = format!("m.{}", go_field(&field.name));
            if field.optional { format!("{member} == nil") } else { zero(&field.kind, &member) }
        })
        .collect();
    match zero.len() {
        0 => out.push_str("\treturn true\n"),
        _ => {
            let _ = writeln!(out, "\treturn {}", zero.join(" &&\n\t\t"));
        }
    }
    out.push_str("}\n");
}

fn zero(kind: &Kind, member: &str) -> String {
    match kind {
        Kind::Bool => format!("!{member}"),
        Kind::Uint | Kind::Duration | Kind::Int | Kind::Int64 | Kind::Time | Kind::Nanos => format!("{member} == 0"),
        Kind::Float => format!("math.Float64bits({member}) == 0"),
        Kind::Str | Kind::Json | Kind::Key => format!("{member} == \"\""),
        Kind::Bin | Kind::List(_) | Kind::Names(_) => format!("len({member}) == 0"),
        Kind::Value => format!("RawIsZero({member})"),
        Kind::Cell => format!("CellIsZero({member})"),
        Kind::Message(_) => format!("{member}.IsZero()"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_run_of_rows_is_padded_as_gofmt_pads_it_and_a_comment_begins_another() {
        let row = |comments: &[&str], cells: &[&str]| Row {
            comments: comments.iter().map(|&line| line.to_owned()).collect(),
            cells: cells.iter().map(|&cell| cell.to_owned()).collect(),
        };
        let mut out = String::new();
        write_rows(
            &mut out,
            &[
                row(&[], &["A", "uint64", "`a`"]),
                row(&[], &["Bb", "[]string", "`b`"]),
                row(&["c"], &["C", "bool", "`c`"]),
            ],
        );
        assert_eq!(out, "\tA  uint64   `a`\n\tBb []string `b`\n\t// c\n\tC bool `c`\n");
        assert_eq!(go_field("ifVersion"), "IfVersion");
    }
}
