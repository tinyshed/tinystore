import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import ts from 'typescript'

import {
	type ApiEngine,
	type ApiLanguage,
	apiEngines,
	apiFile,
	apiIndexFile,
	apiLanguageNames,
	apiLanguages,
} from './api'
